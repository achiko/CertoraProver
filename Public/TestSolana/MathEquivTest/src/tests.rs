#[rule]
pub fn shr63_u64() {
    let x: u64 = nondet();
    clog!(x);
    let r = x >> 63;
    // Constrain the shift result at runtime so the compiler keeps the shift.
    cvlr_assume!(r == 1);
    // Discharging this requires understanding the shift's relation to bit 63.
    cvlr_assert!(x >= 1u64 << 63);
}

#[rule]
pub fn mod_sub_eq_u64() {
    let x: u64 = nondet();
    let y: u64 = nondet();
    clog!(x, y);
    let s = x.wrapping_add(y);
    let r = s.wrapping_sub(0x42);
    // Use r in multiple places to prevent (r == 0 <=> s == 0x42) folding.
    clog!(r);
    cvlr_assume!(r == 0);
    cvlr_assert!(s == 0x42);
}

#[rule]
pub fn mod_and_u64() {
    use cvlr::mathint::NativeInt;
    let x: u64 = nondet();
    let y: u64 = nondet();
    clog!(x, y);
    // wrapping_add yields explicit Mod(Add(x, y), 2^64) in TAC.
    let s: u64 = x.wrapping_add(y);
    // NativeInt::mask emits BWAnd(s, 2^64 - 1).  Combined with the wrapping_add,
    // this is exactly the mod-and shape: x.mod(2^64) & maxUnsigned(64).
    let masked: u64 = NativeInt::from(s).mask(64).into();
    clog!(masked);
    cvlr_assert!(masked == s);
}

#[rule]
pub fn sub_flip_sign_u64() {
    let x: u64 = nondet();
    let y: u64 = nondet();
    clog!(x, y);
    // The sub-flip-sign rewrite handles `Mod(Sub(x, c), 2^64)` where `c` is
    // a 2's-complement-negative constant.  LLVM aggressively canonicalizes a
    // direct `wrapping_sub(<concrete negative>)` into `wrapping_add(<positive>)`,
    // so we route the subtraction through a non-constant `y` and constrain
    // its value at the prover level.  The Sub stays in TAC; whether the
    // sub-flip-sign rewriter picks the constant up depends on how far
    // constant propagation runs before the mod-math passes.
    cvlr_assume!(y == 0xFFFFFFFFFFFFFFFE);
    let r: u64 = x.wrapping_sub(y);
    clog!(r);
    cvlr_assert!(r == x.wrapping_add(2));
}

#[rule]
pub fn signext_mod_sign_i8() {
    use cvlr::mathint::NativeInt;
    let x: u64 = nondet();
    clog!(x);
    // Sign-extend from low 8 bits via shl/arith-shr.  In TAC this is the
    // shl-mod-signext input shape; after that rewrite, leaves
    // Mod(SignExtend(0, x), 2^64).  We then need to compare against
    // maxSigned(64) without LLVM optimizing the comparison into signed
    // form; using NativeInt's own `.le` ensures the comparison stays as
    // an unsigned `Le` with the constant directly in the TAC operand.
    let shifted: u64 = x << 56;
    let arith_shifted: u64 = ((shifted as i64) >> 56) as u64;
    clog!(arith_shifted);
    let nonneg: bool = NativeInt::from(arith_shifted) <= NativeInt::from(0x7FFF_FFFF_FFFF_FFFF_u64);
    cvlr_assert!(nonneg == ((x as u8) < 128));
}

#[rule]
pub fn signext_mod_nonzero_i8() {
    use cvlr::mathint::NativeInt;
    let x: u64 = nondet();
    clog!(x);
    let shifted: u64 = x << 56;
    let arith_shifted: u64 = ((shifted as i64) >> 56) as u64;
    clog!(arith_shifted);
    // Compare against 0 via NativeInt to keep the unsigned `Gt` form.
    // `arith_shifted > 0` (unsigned) is true iff the original low byte is
    // non-zero — when the byte is negative-as-i8, the sign-extended u64 is
    // still non-zero (in fact >= 0xFFFFFFFFFFFFFF80).
    let is_pos: bool = NativeInt::from(arith_shifted) > NativeInt::from(0_u64);
    cvlr_assert!(is_pos == ((x as u8) != 0));
}
