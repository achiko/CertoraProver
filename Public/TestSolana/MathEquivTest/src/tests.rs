#[rule]
pub fn add_no_overflow_u64() {
    let x: u64 = nondet();
    let y: u64 = nondet();
    let r: u64 = x.wrapping_add(y);
    clog!(x, y);
    let no_ovf: bool = r >= x;
    cvlr_assume!(no_ovf);
    // Under the assumption r >= x, wrapping_add equals the true sum (no overflow).
    cvlr_assert!((r as u128) == (x as u128) + (y as u128));
}

#[rule]
pub fn sub_no_borrow_u64() {
    let x: u64 = nondet();
    let y: u64 = nondet();
    let r: u64 = x.wrapping_sub(y);
    clog!(x, y);
    let no_borrow: bool = r <= x;
    cvlr_assume!(no_borrow);
    // Under the assumption r <= x, wrapping_sub equals the true difference (no borrow).
    cvlr_assert!((r as u128) + (y as u128) == (x as u128));
}

#[rule]
pub fn gt_signed_to_unsigned_i64() {
    use cvlr::mathint::NativeInt;
    let x: u64 = nondet();
    let y: u64 = nondet();
    clog!(x, y);
    // NativeInt unsigned comparison on sign-extended values equals signed > on the originals.
    let x_sext = NativeInt::from(x).sext(64);
    let y_sext = NativeInt::from(y).sext(64);
    let lhs = x_sext > y_sext;
    let rhs = (x as i64) > (y as i64);
    cvlr_assert!(lhs == rhs);
}

