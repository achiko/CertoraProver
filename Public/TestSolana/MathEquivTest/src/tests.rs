macro_rules! bin_equiv {
    ($int_type:ty, $rust_fn:ident) => {
        paste! {
            #[rule]
            pub fn [<$rust_fn _ $int_type>]() {
                let x: $int_type = nondet();
                let y: $int_type = nondet();
                let rust = x.$rust_fn(y);
                let native = x.[<n_ $rust_fn>](y);
                clog!(x, y);
                cvlr_assert_eq!(rust, native);
            }
        }
    };
}

macro_rules! un_equiv {
    ($int_type:ty, $rust_fn:ident) => {
        paste! {
            #[rule]
            pub fn [<$rust_fn _ $int_type>]() {
                let x: $int_type = nondet();
                let rust = x.$rust_fn();
                let native = x.[<n_ $rust_fn>]();
                clog!(x);
                cvlr_assert_eq!(rust, native);
            }
        }
    };
}

macro_rules! for_signed {
    ($equiv:ident, $rust_fn:ident) => {
        $equiv!(i64, $rust_fn);
        $equiv!(i128, $rust_fn);
    };
}

macro_rules! for_unsigned {
    ($equiv:ident, $rust_fn:ident) => {
        $equiv!(u64, $rust_fn);
        $equiv!(u128, $rust_fn);
    };
}

macro_rules! for_all {
    ($equiv:ident, $rust_fn:ident) => {
        for_signed!($equiv, $rust_fn);
        for_unsigned!($equiv, $rust_fn);
    };
}

